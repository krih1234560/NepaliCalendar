const holidayContainer =
  document.getElementById(
    "holidayMonths"
  );


function renderHolidays(
  filter = "all"
) {

  holidayContainer.innerHTML = "";


  holidays2083.forEach((month) => {

    const events =
      month.events.filter((event) => {

        if (filter === "all") {
          return true;
        }

        return event.type === filter;

      });


    if (!events.length) {
      return;
    }


    const monthCard =
      document.createElement("section");

    monthCard.className =
      "holiday-month";


    monthCard.innerHTML = `

      <div class="holiday-month-header">

        <div>

          <span>
            ${month.month}
          </span>

          <h2>
            ${month.nepaliMonth} २०८३
          </h2>

        </div>

        <small>
          ${month.period}
        </small>

      </div>


      <div class="holiday-list">

        ${events.map((event) => `

          <article
            class="holiday-item ${event.type}"
          >

            <div class="holiday-date">

              <strong>
                ${event.bs}
              </strong>

              <small>
                BS
              </small>

            </div>


            <div class="holiday-info">

              <h3>
                ${event.name}
              </h3>

              <p>
                ${event.nepali}
              </p>

              <span class="holiday-ad">
                ${event.ad}
              </span>

            </div>


            <span
              class="holiday-badge"
            >
              ${
                event.type === "government"
                  ? "Government Holiday"
                  : "Festival"
              }
            </span>

          </article>

        `).join("")}

      </div>

    `;


    holidayContainer.appendChild(
      monthCard
    );

  });

}


document
  .querySelectorAll(
    ".holiday-filter"
  )
  .forEach((button) => {

    button.addEventListener(
      "click",
      () => {

        document
          .querySelectorAll(
            ".holiday-filter"
          )
          .forEach((item) => {

            item.classList.remove(
              "active"
            );

          });


        button.classList.add(
          "active"
        );


        renderHolidays(
          button.dataset.filter
        );

      }
    );

  });


renderHolidays();


